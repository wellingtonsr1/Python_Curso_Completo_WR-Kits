#!/usr/bin/python3

print("\nLista, Tupla e Dicionário")
print("----------------------------")

lista = [1, 2, 3, 4, 5, [0, 1, 2, 'a', 'b', 'c', 3, 4, 5]]
print("Lista     :", lista)

tupla = (1, 2, 3, 4, 5, [0, 1, 2, 'a', 'b', 'c', 3, 4, 5])
print("Tupla     :", tupla)

dicionario = {'a': 1, 'b': 2, 'c': 3, 'd': 4, 'e': 5, 'f': [0, 1, 2, 'a', 'b', 'c', 3, 4, 5]}
print("Dicionário:", dicionario)

# A diferença entre os três tipos de dados é que a lista é mutável, ou seja, 
# podemos alterar seus elementos, enquanto a tupla é imutável, ou seja, 
# não podemos alterar seus elementos. O dicionário é uma coleção de pares 
# chave-valor, onde cada chave é única e pode ser usada para acessar seu 
# valor correspondente.

print("\n") # Imprime uma linha em branco para separar a saída dos dados anteriores





